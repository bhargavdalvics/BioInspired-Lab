"""
Load Balancing using Ant Colony Optimization (ACO) for the Travelling Salesman Problem
-------------------------------------------------------------------------------------
Two solvers are provided:

1. ACO for the classic TSP (one salesman visits every city once and returns home).
2. Load-balanced ACO for the multiple-TSP (m salesmen / vehicles / servers share
   the cities). The goal is to spread the work evenly: minimise the LONGEST tour
   (the makespan) so no salesman is overloaded, using total distance as a tie-breaker.

Load balancing happens in two places:
  * During construction, an ant always extends the tour of the currently
    least-loaded salesman, so work is shared out as it is built.
  * Pheromone is deposited in proportion to 1 / makespan, so the colony learns
    edges that lead to balanced solutions rather than just short ones.

Requires: numpy (matplotlib optional, for plotting).
"""

import numpy as np


# ----------------------------------------------------------------------------
# Helpers
# ----------------------------------------------------------------------------
def distance_matrix(coords):
    """Euclidean distance matrix for an (n, 2) array of coordinates."""
    diff = coords[:, None, :] - coords[None, :, :]
    return np.sqrt((diff ** 2).sum(axis=2))


def tour_length(tour, dist):
    """Length of a closed tour (returns to its first city)."""
    if len(tour) < 2:
        return 0.0
    return float(sum(dist[tour[i], tour[i + 1]] for i in range(len(tour) - 1))
                 + dist[tour[-1], tour[0]])


# ----------------------------------------------------------------------------
# Ant Colony Optimization
# ----------------------------------------------------------------------------
class AntColony:
    def __init__(self, dist, n_ants=30, n_iterations=200, alpha=1.0, beta=3.0,
                 rho=0.1, q=100.0, seed=None):
        """
        dist         : (n x n) distance matrix
        n_ants       : ants per iteration
        n_iterations : number of iterations
        alpha        : pheromone importance
        beta         : heuristic (1/distance) importance
        rho          : pheromone evaporation rate (0..1)
        q            : pheromone deposit constant
        """
        self.dist = np.asarray(dist, dtype=float)
        self.n = len(self.dist)
        self.n_ants = n_ants
        self.n_iterations = n_iterations
        self.alpha, self.beta, self.rho, self.q = alpha, beta, rho, q
        self.rng = np.random.default_rng(seed)

        with np.errstate(divide="ignore"):
            self.eta = 1.0 / self.dist          # heuristic desirability
        self.eta[~np.isfinite(self.eta)] = 0.0
        self.tau = np.ones((self.n, self.n))    # initial pheromone

    # --- core probabilistic choice -------------------------------------------
    def _choose_next(self, current, unvisited):
        cand = np.fromiter(unvisited, dtype=int)
        weights = (self.tau[current, cand] ** self.alpha) * (self.eta[current, cand] ** self.beta)
        total = weights.sum()
        if total <= 0:
            return int(self.rng.choice(cand))
        return int(self.rng.choice(cand, p=weights / total))

    def _evaporate(self):
        self.tau *= (1.0 - self.rho)
        self.tau = np.maximum(self.tau, 1e-10)  # keep it positive

    def _deposit(self, tour, amount):
        for i in range(len(tour)):
            a, b = tour[i], tour[(i + 1) % len(tour)]
            self.tau[a, b] += amount
            self.tau[b, a] += amount

    # --- 1. classic single-salesman TSP --------------------------------------
    def solve_tsp(self, start=0, verbose=True):
        best_tour, best_len, history = None, np.inf, []

        for it in range(self.n_iterations):
            tours = []
            for _ in range(self.n_ants):
                tour = [start]
                unvisited = set(range(self.n)) - {start}
                while unvisited:
                    nxt = self._choose_next(tour[-1], unvisited)
                    tour.append(nxt)
                    unvisited.remove(nxt)
                tours.append((tour, tour_length(tour, self.dist)))

            self._evaporate()
            for tour, length in tours:
                self._deposit(tour, self.q / length)

            it_best = min(tours, key=lambda t: t[1])
            if it_best[1] < best_len:
                best_tour, best_len = it_best
            self._deposit(best_tour, self.q / best_len)  # elitist reinforcement
            history.append(best_len)

            if verbose and (it % 50 == 0 or it == self.n_iterations - 1):
                print(f"[TSP] iter {it:4d}  best length = {best_len:.2f}")

        return best_tour, best_len, history

    # --- 2. load-balanced multiple-salesman TSP -------------------------------
    def solve_balanced(self, n_salesmen=3, depot=0, verbose=True):
        """
        Every salesman starts and ends at `depot`. Cities are shared so that the
        maximum tour length (the heaviest load) is as small as possible.
        """
        best, best_key, history = None, (np.inf, np.inf), []

        for it in range(self.n_iterations):
            solutions = []
            for _ in range(self.n_ants):
                tours = [[depot] for _ in range(n_salesmen)]
                loads = np.zeros(n_salesmen)
                unvisited = set(range(self.n)) - {depot}

                while unvisited:
                    # Load balancing: extend the least-loaded salesman's route.
                    # Include the cost of returning to the depot so loads compare fairly.
                    projected = [loads[k] + self.dist[tours[k][-1], depot] for k in range(n_salesmen)]
                    k = int(np.argmin(projected))
                    cur = tours[k][-1]
                    nxt = self._choose_next(cur, unvisited)
                    loads[k] += self.dist[cur, nxt]
                    tours[k].append(nxt)
                    unvisited.remove(nxt)

                lengths = [tour_length(t, self.dist) for t in tours]
                key = (max(lengths), sum(lengths))   # (makespan, total distance)
                solutions.append((tours, lengths, key))

            self._evaporate()
            for tours, lengths, key in solutions:
                amount = self.q / key[0]             # reward balanced solutions
                for t in tours:
                    if len(t) > 1:
                        self._deposit(t, amount)

            it_best = min(solutions, key=lambda s: s[2])
            if it_best[2] < best_key:
                best, best_key = it_best, it_best[2]
            for t in best[0]:                        # elitist reinforcement
                if len(t) > 1:
                    self._deposit(t, self.q / best_key[0])
            history.append(best_key[0])

            if verbose and (it % 50 == 0 or it == self.n_iterations - 1):
                print(f"[Balanced] iter {it:4d}  makespan = {best_key[0]:.2f}  "
                      f"total = {best_key[1]:.2f}")

        tours, lengths, _ = best
        return tours, lengths, history


# ----------------------------------------------------------------------------
# Reporting / plotting
# ----------------------------------------------------------------------------
def report_balance(lengths):
    lengths = np.array(lengths)
    mean = lengths.mean()
    print("\nLoad per salesman:")
    for i, L in enumerate(lengths):
        print(f"  Salesman {i + 1}: {L:8.2f}")
    print(f"  Makespan (max load) : {lengths.max():.2f}")
    print(f"  Total distance      : {lengths.sum():.2f}")
    print(f"  Std deviation       : {lengths.std():.2f}")
    print(f"  Imbalance (max/mean): {lengths.max() / mean:.3f}  (1.000 = perfectly balanced)")


def plot_results(coords, tsp_tour, balanced_tours, depot=0):
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not installed - skipping plot.")
        return

    fig, axes = plt.subplots(1, 2, figsize=(13, 6))

    ax = axes[0]
    path = tsp_tour + [tsp_tour[0]]
    ax.plot(coords[path, 0], coords[path, 1], "-o", ms=4)
    ax.set_title(f"Single-salesman TSP (length {tour_length(tsp_tour, distance_matrix(coords)):.1f})")

    ax = axes[1]
    dist = distance_matrix(coords)
    for i, t in enumerate(balanced_tours):
        path = t + [t[0]]
        ax.plot(coords[path, 0], coords[path, 1], "-o", ms=4,
                label=f"Salesman {i + 1}: {tour_length(t, dist):.1f}")
    ax.set_title("Load-balanced multi-salesman TSP")
    ax.legend()

    for ax in axes:
        ax.plot(*coords[depot], "k*", ms=16, label="Depot")
        ax.set_aspect("equal")
    plt.tight_layout()
    plt.savefig("aco_tsp_result.png", dpi=120)
    print("\nPlot saved to aco_tsp_result.png")
    plt.show()


